/* global console, process */
// Writes src/species/catalog.ts (one named camelCase export per Species) and src/species/loaders.ts
// (SpeciesName and the dynamic imports behind `loadSpecies` / `SPECIES_NAMES`) from the Species JSON
// files in src/species/data/ (one file per Species, named by its kebab-case id), sorted by id.
//
//   node scripts/generate-species.mjs          (npm run species) rewrite the catalog
//   node scripts/generate-species.mjs --check  exit 1 when the catalog is out of date
//
// Adding a Species = adding its JSON file and running this; on a merge conflict in a generated file,
// take either side and run it again.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(fileURLToPath(import.meta.url), '../..');
export const DATA_DIR = resolve(root, 'src/species/data');
const SPECIES_SRC = resolve(root, 'src/species');

/** Kebab-case id -> camelCase export name ('douglas-fir' -> 'douglasFir'). */
export const exportName = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** Ids of the Species JSON files in `dir`, sorted. */
export function speciesIds(dir = DATA_DIR) {
  return readdirSync(dir)
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();
}

const HEADER = '// GENERATED by scripts/generate-species.mjs from src/species/data/*.json; do not edit, run `npm run species`.';

/** The generated sources (file name in src/species/ -> source) for the Species JSON files in `dir`. */
export function speciesSources(dir = DATA_DIR) {
  const species = speciesIds(dir).map((id) => {
    if (!/^[a-z]+(-[a-z]+)*$/.test(id)) throw new Error(`Species file "${id}.json": the name must be a kebab-case id.`);
    const data = JSON.parse(readFileSync(resolve(dir, `${id}.json`), 'utf8'));
    if (data.id !== id) throw new Error(`Species file "${id}.json" has id "${data.id}"; they must match.`);
    return { id, name: exportName(id), label: `${data.name} (${data.form})` };
  });
  const catalog = [
    HEADER,
    '// One named export per Species, each its own module (tree-shakeable).',
    "import type { SpeciesName } from './loaders';",
    "import type { SpeciesDefinition } from './types';",
    ...species.map(({ id, name }) => `import ${name}Data from './data/${id}.json';`),
    ...species.flatMap(({ name, label }) => ['', `/** ${label}. */`, `export const ${name} = ${name}Data as SpeciesDefinition;`]),
    '',
    '/** Every Species by id (for pickers that list them all; importing one Species by name bundles only that one). */',
    'export const SPECIES_BY_NAME: Readonly<Record<SpeciesName, SpeciesDefinition>> = {',
    ...species.map(({ id, name }) => `  '${id}': ${name},`),
    '};',
    '',
  ];
  const loaders = [
    HEADER,
    '',
    '/** Id of a Species in the collection (kebab-case), e.g. `\'oak\'`. */',
    `export type SpeciesName =${species.map(({ id }) => `\n  | '${id}'`).join('')};`,
    '',
    '/** Dynamic import of each Species (its own chunk in the build), by id. */',
    'export const SPECIES_LOADERS: Record<SpeciesName, () => Promise<{ default: unknown }>> = {',
    ...species.map(({ id }) => `  '${id}': () => import('./data/${id}.json'),`),
    '};',
    '',
  ];
  return { 'catalog.ts': catalog.join('\n'), 'loaders.ts': loaders.join('\n') };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  for (const [file, source] of Object.entries(speciesSources())) {
    const path = resolve(SPECIES_SRC, file);
    if (!check) {
      writeFileSync(path, source);
      console.log(`Wrote ${path}`);
    } else if (readFileSync(path, 'utf8') !== source) {
      console.error(`src/species/${file} is out of date: run \`npm run species\`.`);
      process.exitCode = 1;
    }
  }
}
