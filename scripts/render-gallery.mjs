/* global console, process */
// The Species gallery: renders every Species in every Style with the e2e renderer (headless Chromium,
// SwiftShader WebGPU, through examples/vanilla), in summer plus a ripe-Fruit shot (seasonal Fruit) and an
// autumn shot (deciduous broadleaves), both chosen from the Species data, and writes
//   docs/species/images/<id>-<style>[-fruit|-autumn].jpg   (JPEG, 400 x 400)
//   docs/species/contact-sheet.jpg                         (every Species in all three Styles, summer)
//   docs/species/README.md                                 (the gallery page)
//
//   npm run gallery                    everything (a few minutes)
//   npm run gallery -- oak birch       re-render only these Species (the page and contact sheet always)
//   npm run gallery -- --no-render     only rewrite the page and the contact sheet from the images on disk
//   --port=5197                        dev server port (default 5197)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DATA_DIR, exportName, speciesIds } from './generate-species.mjs';
import { startSpeciesRenderer, STYLES, SUMMER } from './species-renderer.mjs';

const root = resolve(fileURLToPath(import.meta.url), '../..');
const DOCS = resolve(root, 'docs/species');
const IMAGES = resolve(DOCS, 'images');
const SIZE = 400;
const QUALITY = 80;
const SEED = 1;

const load = (id) => JSON.parse(readFileSync(resolve(DATA_DIR, `${id}.json`), 'utf8'));

/** The Fruit shot: for Species whose Fruit comes and goes over the year, when the Fruit is ripe (its last colour). */
function fruitShot(species) {
  const amount = species.fruit ? species.season.fruit : undefined;
  if (!amount || amount.every((k) => k.value === amount[0].value)) return undefined;
  const lastFull = amount.filter((k) => k.value >= 1).at(-1).t;
  const ripe = species.season.fruitColor?.at(-1)?.t ?? lastFull;
  return { name: 'fruit', label: 'with Fruit', season: Math.min(ripe, lastFull) };
}

/** The autumn shot: for broadleaves that drop their leaves, on their last day of full leaf (coloured, not yet falling). */
function autumnShot(species) {
  const coverage = species.season.leafCoverage;
  if (species.form !== 'broadleaf' || !coverage.some((k) => k.value === 0)) return undefined;
  return { name: 'autumn', label: 'autumn', season: coverage.filter((k) => k.value >= 1).at(-1).t };
}

/** The extra shots of a Species, from its data: ripe Fruit (seasonal Fruit) and autumn (deciduous broadleaves). */
export function extraShots(species) {
  return [fruitShot(species), autumnShot(species)].filter(Boolean);
}

/** Image file names (relative to docs/species/) of one Species: summer per Style, plus the extra shots. */
export function shots(species) {
  return STYLES.flatMap((style) => [
    { style, shot: 'summer', label: 'summer', season: SUMMER, file: `images/${species.id}-${style}.jpg` },
    ...extraShots(species).map((extra) => ({
      style,
      shot: extra.name,
      label: extra.label,
      season: extra.season,
      file: `images/${species.id}-${style}-${extra.name}.jpg`,
    })),
  ]);
}

/** Roots per Stem from which a Species counts as strong-rooted (the strong Roots tier) and gets a "Roots" tag. */
const STRONG_ROOTS = 7;

const traits = (s) =>
  [
    `${s.form}`,
    `${s.foliage.type} leaves`,
    `${s.bark.type} bark`,
    s.fruit ? `Fruit: ${s.fruit.type}` : null,
    (s.roots?.count ?? 0) >= STRONG_ROOTS ? 'Roots' : null,
    (s.trunk.stems ?? 1) > 1 ? `${s.trunk.stems} Stems` : null,
  ]
    .filter(Boolean)
    .join(' · ');

/** The gallery page (Markdown) for these Species. */
export function galleryPage(list) {
  const anchors = (form) =>
    list
      .filter((s) => s.form === form)
      .map((s) => `[${s.name}](#${s.name.toLowerCase().replace(/\s+/g, '-')})`)
      .join(' · ');
  const out = [
    '# Species gallery',
    '',
    `<!-- GENERATED by scripts/render-gallery.mjs (\`npm run gallery\`); do not edit by hand. -->`,
    '',
    `All ${list.length} Species of \`@casmo/tree.js/species\` in the three built-in Styles (Seed ${SEED}, summer = Season ${SUMMER}),`,
    'plus a shot with ripe Fruit for Species with seasonal Fruit and an autumn shot for the deciduous broadleaves. Each Species is',
    'plain JSON; any Style turns it into a Tree Definition: `createTree(lowPoly.apply(oak), { seed: 1 })`.',
    'Images are rendered by `npm run gallery` with the same renderer as the e2e tests (SwiftShader WebGPU).',
    'Try them live in [`examples/species`](../../examples/species/main.ts) or start from one in the Tree Editor.',
    '',
    `- **Broadleaf**: ${anchors('broadleaf')}`,
    `- **Conifer**: ${anchors('conifer')}`,
    '',
    '![Every Species in the low-poly, stylized and realistic Styles](contact-sheet.jpg)',
  ];
  for (const species of list) {
    const all = shots(species);
    const rows = [...new Set(all.map((s) => s.shot))].map((shot) => {
      const cells = STYLES.map((style) => {
        const s = all.find((x) => x.shot === shot && x.style === style);
        return `<img src="${s.file}" width="200" alt="${species.name}, ${style}, ${s.label}">`;
      });
      return `| ${all.find((x) => x.shot === shot).label} | ${cells.join(' | ')} |`;
    });
    const name = exportName(species.id);
    out.push(
      '',
      `## ${species.name}`,
      '',
      `\`${name}\` · ${traits(species)} · [${species.id}.json](../../src/species/data/${species.id}.json)`,
      '',
      `| | ${STYLES.join(' | ')} |`,
      '| --- | --- | --- | --- |',
      ...rows,
      '',
      '```ts',
      "import { createTree } from '@casmo/tree.js';",
      `import { ${name} } from '@casmo/tree.js/species';`,
      "import lowPoly from '@casmo/tree.js/styles/low-poly';",
      '',
      `const tree = createTree(lowPoly.apply(${name}), { seed: ${SEED} });`,
      '```',
    );
  }
  return out.join('\n') + '\n';
}

/** HTML of the contact sheet: a grid of Species, each with its three Styles side by side (summer). */
function contactSheetHtml(list) {
  const tile = 120;
  const data = (file) => `data:image/jpeg;base64,${readFileSync(resolve(DOCS, file)).toString('base64')}`;
  const cells = list
    .map((s) => {
      const images = STYLES.map((style) => `<img src="${data(`images/${s.id}-${style}.jpg`)}">`).join('');
      return `<figure><div>${images}</div><figcaption>${s.name}</figcaption></figure>`;
    })
    .join('');
  return `<!doctype html><html><head><style>
    body { margin: 0; background: #f4f7f9; font: 600 15px system-ui, sans-serif; color: #23323d; }
    main { display: grid; grid-template-columns: repeat(4, ${tile * 3}px); gap: 10px 14px; padding: 12px; width: max-content; }
    figure { margin: 0; } figure div { display: flex; } img { width: ${tile}px; height: ${tile}px; display: block; }
    figcaption { padding: 3px 2px 0; } header { grid-column: 1 / -1; font-weight: 400; }
  </style></head><body><main><header>tree.js Species · each: ${STYLES.join(', ')} · summer, Seed ${SEED}</header>${cells}</main></body></html>`;
}

async function main() {
  const args = process.argv.slice(2);
  const options = Object.fromEntries(args.filter((a) => a.startsWith('--')).map((a) => [...a.slice(2).split('='), true].slice(0, 2)));
  const ids = args.filter((a) => !a.startsWith('--'));
  const list = speciesIds().map(load);
  mkdirSync(IMAGES, { recursive: true });

  const renderer = await startSpeciesRenderer({ port: Number(options.port ?? 5197), size: SIZE });
  try {
    if (!options['no-render']) {
      for (const species of list.filter((s) => ids.length === 0 || ids.includes(s.id))) {
        for (const shot of shots(species)) {
          const path = resolve(DOCS, shot.file);
          await renderer.render({ id: species.id, style: shot.style, season: shot.season, seed: SEED, path, type: 'jpeg', quality: QUALITY });
          console.log(path);
        }
      }
    }
    const page = await renderer.browser.newPage({ viewport: { width: 800, height: 600 } });
    await page.setContent(contactSheetHtml(list));
    const sheet = resolve(DOCS, 'contact-sheet.jpg');
    await page.locator('main').screenshot({ path: sheet, type: 'jpeg', quality: QUALITY });
    console.log(sheet);
  } finally {
    await renderer.close();
  }
  writeFileSync(resolve(DOCS, 'README.md'), galleryPage(list));
  console.log(resolve(DOCS, 'README.md'));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
